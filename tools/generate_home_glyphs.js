/**
 * Kiroku Note Desktop — Home Screen Stroke Glyphs Generator
 * Reads source SVGs from desktop/src/ui/assets/, recolors hardcoded hex to currentColor,
 * ensures unique namespaces for all element IDs and url(#...) references, and exports
 * clean, inlinable SVG template strings for zero-fetch, zero-CSP runtime mounting.
 *
 * Golden Rule: Zero emojis anywhere across code, UI, or logs.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const hiraganaPath = path.join(repoRoot, 'desktop', 'src', 'ui', 'assets', 'hiragana_a.svg');
const kanjiPath = path.join(repoRoot, 'desktop', 'src', 'ui', 'assets', 'kanji_dai.svg');
const outputPath = path.join(repoRoot, 'desktop', 'src', 'ui', 'assets', 'home_glyphs.js');

function processSvg(rawSvg, prefix) {
  let processed = rawSvg;

  // 1. Replace hardcoded colors with currentColor
  processed = processed.replace(/#333c45/gi, 'currentColor');
  processed = processed.replace(/#000000/gi, 'currentColor');

  // 2. Identify all IDs and disambiguate duplicates
  const idCounts = new Map();
  // Pass 1: count occurrences of each ID
  const idRegex = /id="([^"]+)"/g;
  let match;
  while ((match = idRegex.exec(processed)) !== null) {
    const id = match[1];
    idCounts.set(id, (idCounts.get(id) || 0) + 1);
  }

  // Pass 2: Replace IDs with namespaced and disambiguated versions
  const idOccurrence = new Map();
  const idReplacementMap = new Map();

  processed = processed.replace(/id="([^"]+)"/g, (_, id) => {
    const total = idCounts.get(id) || 1;
    let newId;
    if (total > 1) {
      const occ = (idOccurrence.get(id) || 0) + 1;
      idOccurrence.set(id, occ);
      newId = `${prefix}${id}-${occ}`;
      // Map the base ID if not already mapped or if it was referenced
      if (!idReplacementMap.has(id)) {
        idReplacementMap.set(id, newId);
      }
    } else {
      newId = `${prefix}${id}`;
      idReplacementMap.set(id, newId);
    }
    return `id="${newId}"`;
  });

  // 3. Update all url(#...) references
  processed = processed.replace(/url\(#([^)]+)\)/g, (fullMatch, refId) => {
    const targetId = idReplacementMap.get(refId) || `${prefix}${refId}`;
    return `url(#${targetId})`;
  });

  // 4. Update all href="#..." or xlink:href="#..." references
  processed = processed.replace(/(href=")#([^"]+)(")/g, (fullMatch, p1, refId, p3) => {
    const targetId = idReplacementMap.get(refId) || `${prefix}${refId}`;
    return `${p1}#${targetId}${p3}`;
  });

  // 5. Ensure SVG has aria-hidden="true" and focusable="false" for decorative glyphs
  if (!processed.includes('aria-hidden=')) {
    processed = processed.replace('<svg ', '<svg aria-hidden="true" focusable="false" ');
  }

  return processed.trim();
}

export function generateHomeGlyphs() {
  const hiraganaRaw = fs.readFileSync(hiraganaPath, 'utf8');
  const kanjiRaw = fs.readFileSync(kanjiPath, 'utf8');

  const hiraganaProcessed = processSvg(hiraganaRaw, 'glyph-vocab-');
  const kanjiProcessed = processSvg(kanjiRaw, 'glyph-kanji-');

  const fileContent = `/**
 * Kiroku Note Desktop — Processed Animated Stroke-Order Glyphs
 * AUTO-GENERATED by tools/generate_home_glyphs.js
 * Source of truth:
 *   - desktop/src/ui/assets/hiragana_a.svg (あ, 5.005s SMIL loop)
 *   - desktop/src/ui/assets/kanji_dai.svg (大, 5s SMIL brush reveal)
 *
 * Color tokens: Hardcoded #333c45 and #000000 converted to currentColor.
 * Unique Namespaces: IDs and url(#...) clipPath references prefixed per glyph.
 *
 * Golden Rule: Zero emojis anywhere across code, UI, or logs.
 */

export const HIRAGANA_A_SVG = ${JSON.stringify(hiraganaProcessed)};

export const KANJI_DAI_SVG = ${JSON.stringify(kanjiProcessed)};

export const HOME_GLYPHS = {
  vocab: HIRAGANA_A_SVG,
  kanji: KANJI_DAI_SVG
};
`;

  fs.writeFileSync(outputPath, fileContent, 'utf8');
  console.log(`[Glyphs] Successfully generated ${outputPath}`);
}

// Execute if run directly
if (process.argv[1] && process.argv[1].endsWith('generate_home_glyphs.js')) {
  generateHomeGlyphs();
}

